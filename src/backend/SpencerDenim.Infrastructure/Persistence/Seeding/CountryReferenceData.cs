using SpencerDenim.Domain.Reference;
using SpencerDenim.Domain.Sales;

namespace SpencerDenim.Infrastructure.Persistence.Seeding;

/// <summary>One <c>ref.Countries</c> seed row: ISO 3166-1 alpha-2, English short name, overseas region.</summary>
public sealed record CountrySeed(string Code, string Name, string? RegionCode);

/// <summary>One <c>sales.DeliveryRegions</c> seed row. The fee is a placeholder for the owner.</summary>
public sealed record DeliveryRegionSeed(
    string Code,
    string Name,
    decimal Fee,
    byte EstimatedDaysMin,
    byte EstimatedDaysMax,
    short SortOrder);

